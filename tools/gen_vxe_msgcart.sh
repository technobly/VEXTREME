#!/bin/bash
# gen_vxe_msgcart.sh - assemble code/app6809/VxeMsg/VxeMsg.asm and write code/stm32/vxe/vxe_msgcart.h, the byte array
# the kernel serves when it refuses a .vxe (vxe/vxe_install.c). The generated header is committed, so a kernel build
# needs no 6809 assembler; run this only after changing VxeMsg.asm.
# Usage (from the repo root): tools/gen_vxe_msgcart.sh        (needs the Docker image `asm6809`, or asm6809 on PATH)
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT/code/app6809"
if command -v asm6809 >/dev/null 2>&1; then asm6809 -B -o VxeMsg/VxeMsg.bin VxeMsg/VxeMsg.asm
else docker run --rm -v "$PWD":/build -w /build -u "$(id -u):$(id -g)" asm6809 asm6809 -B -o VxeMsg/VxeMsg.bin VxeMsg/VxeMsg.asm; fi
python3 -I - VxeMsg/VxeMsg.bin "$ROOT/code/stm32/vxe/vxe_msgcart.h" <<'PY'
import sys
b = open(sys.argv[1], "rb").read()
OFS, LEN, N = 0x100, 20, 8
assert len(b) > OFS + LEN * N, "image ends before the text slots"
assert all(x == 0 for x in b[OFS:OFS + LEN * N]), "text slots must assemble as zeros"
rows = []
for i in range(0, len(b), 16):
    rows.append("    " + ", ".join("0x%02X" % x for x in b[i:i + 16]) + ",")
open(sys.argv[2], "w").write(
"""/* vxe_msgcart.h - GENERATED by tools/gen_vxe_msgcart.sh from code/app6809/VxeMsg/VxeMsg.asm. Do not edit.
 * The message cartridge the kernel serves when it refuses a .vxe (see vxe_install.c). The eight text slots
 * at VXE_MSG_OFS are zero here; the kernel writes the lines in. */
#ifndef VXE_MSGCART_H
#define VXE_MSGCART_H
#define VXE_MSG_OFS    0x%X
#define VXE_MSG_LEN    %d     /* bytes per slot: up to %d characters, then $80 */
#define VXE_MSG_LINES  %d
static const unsigned char vxe_msgcart[%d] = {
%s
};
#endif
""" % (OFS, LEN, LEN - 1, N, len(b), "\n".join(rows).rstrip(",")))
print("wrote", sys.argv[2], len(b), "bytes")
PY
